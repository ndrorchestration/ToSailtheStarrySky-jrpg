#!/usr/bin/env python3
"""Optional Unreal Editor Python entry: import ten original QA WAV previews.

DO NOT run automatically; requires explicit opt-in and a scratch WAV folder
containing the SHA-256 receipt generated by build_audio_preview_samples.py.
This intentionally does not save, replace, cook, publish, or package assets.
"""
from __future__ import annotations
import ctypes
import hashlib
import json
import os
from pathlib import Path
import shutil
import wave

EXPECTED = frozenset({
    "ui_confirm.wav", "repair_attuned.wav", "engine_warning.wav",
    "mystery_echo.wav", "weather_gust.wav", "splashdown_review.wav",
    "footstep_wood.wav", "footstep_sand.wav", "footstep_stone.wav", "footstep_metal.wav",
})
DESTINATION = "/Game/TSTSS/Audio/QAReview"
OPT_IN = "I_APPROVE_QA_AUDIO_IMPORT_ONLY"
MIN_RAM_BYTES = int(6.5 * 1024 ** 3)
MIN_DISK_BYTES = 14 * 1024 ** 3


def available_ram_bytes() -> int:
    if os.name != "nt":
        raise RuntimeError("Windows-only review import; cannot establish RAM safely")
    class MEMORYSTATUSEX(ctypes.Structure):
        _fields_ = [
            ("dwLength", ctypes.c_ulong),
            ("dwMemoryLoad", ctypes.c_ulong),
            ("ullTotalPhys", ctypes.c_ulonglong),
            ("ullAvailPhys", ctypes.c_ulonglong),
            ("ullTotalPageFile", ctypes.c_ulonglong),
            ("ullAvailPageFile", ctypes.c_ulonglong),
            ("ullTotalVirtual", ctypes.c_ulonglong),
            ("ullAvailVirtual", ctypes.c_ulonglong),
            ("ullAvailExtendedVirtual", ctypes.c_ulonglong),
        ]
    status = MEMORYSTATUSEX()
    status.dwLength = ctypes.sizeof(status)
    if not ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status)):
        raise RuntimeError("Cannot attest to available RAM")
    return int(status.ullAvailPhys)


def verify_source(folder: Path) -> list[Path]:
    folder = folder.resolve(strict=True)
    if "content" in {p.lower() for p in folder.parts}:
        raise RuntimeError("QA source must be outside Unreal Content")
    receipt_path = folder / "audio_preview_receipt.json"
    if not receipt_path.is_file():
        raise RuntimeError("Missing governed SHA-256 receipt")
    receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
    if receipt.get("status") != "ORIGINAL_REVIEW_SYNTHETIC_NOT_NATIVE_VERIFIED":
        raise RuntimeError("Receipt not classified as QA-only")
    recorded = receipt.get("files", [])
    names = [row.get("filename") for row in recorded]
    if set(names) != EXPECTED or len(names) != len(EXPECTED):
        raise RuntimeError("Unrecognized WAV selection; fail closed")
    paths = []
    for record in recorded:
        name = record["filename"]
        path = folder / name
        if not path.is_file() or path.is_symlink() or path.stat().st_size > 3_000_000:
            raise RuntimeError("Missing, linked, or oversized review WAV: " + name)
        with wave.open(str(path), "rb") as wav:
            if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) != (1, 2, 48000):
                raise RuntimeError("Unexpected preview sample format: " + name)
            if wav.getnframes() < 1000:
                raise RuntimeError("Empty preview file")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != record.get("sha256"):
            raise RuntimeError("Preview WAV hash mismatch: " + name)
        if record.get("production_approved") is not False:
            raise RuntimeError("Wrong approval scope")
        paths.append(path)
    return paths


def main():
    if os.environ.get("TSTSS_AUDIO_REVIEW_OPT_IN") != OPT_IN:
        raise RuntimeError("Explicit QA import opt-in missing; no write attempted")
    source = os.environ.get("TSTSS_AUDIO_REVIEW_SOURCE")
    if not source:
        raise RuntimeError("TSTSS_AUDIO_REVIEW_SOURCE not set")
    paths = verify_source(Path(source))
    if available_ram_bytes() < MIN_RAM_BYTES:
        raise RuntimeError("Below minimum 6.5 GiB free physical RAM; abort")
    if shutil.disk_usage(Path(source)).free < MIN_DISK_BYTES:
        raise RuntimeError("Below minimum 14 GiB scratch disk; abort")
    import unreal
    if shutil.disk_usage(unreal.Paths.project_dir()).free < MIN_DISK_BYTES:
        raise RuntimeError("Below minimum 14 GiB project disk; abort")
    library = unreal.get_editor_subsystem(unreal.EditorAssetSubsystem)
    tasks = []
    for file in sorted(paths):
        name = "QA_" + file.stem
        asset = DESTINATION + "/" + name
        if library.does_asset_exist(asset):
            raise RuntimeError("QA review asset would overwrite existing content: " + asset)
        task = unreal.AssetImportTask()
        task.filename = str(file)
        task.destination_path = DESTINATION
        task.destination_name = name
        task.automated = True
        task.replace_existing = False
        task.save = False  # intentionally transient; editor audition, not release.
        tasks.append(task)
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)
    imported = [str(path) for task in tasks for path in task.imported_object_paths]
    if len(imported) != len(EXPECTED):
        raise RuntimeError("Preview import incomplete; discard unsaved QA packages")
    unreal.log("TSTSS QA audio imports created but UNSAVED: " + "; ".join(imported))
    return imported

if __name__ == "__main__":
    main()

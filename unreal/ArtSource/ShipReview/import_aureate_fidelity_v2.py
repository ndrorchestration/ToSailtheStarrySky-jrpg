#!/usr/bin/env python3
"""Fail-closed optional UE 5.8 Editor import for V2 approved-direction lookdev.

The creator-approved art is the reference, NOT this procedural mesh. This tool
never binds the ship actor, alters a map, unlocks Orbiter, or claims fidelity.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

from build_aureate_fidelity_v2 import (
    FILES, APPROVED_IMAGE_SHA256, write_or_verify,
)

DESTINATIONS = (
    "/Game/TSTSS/Review/ShipArt/IvoryHullCandidateV2",
    "/Game/TSTSS/Review/ShipArt/BlueGlassBridgeCandidateV2",
)
# Unreal centimeters, X forward, Z up. These are *intake bounds only*, not
# approved scale. Re-review before accepting real crew-size geometry.
EXTENT_BANDS_CM = (
    ((650, 900), (120, 320), (40, 150)),
    ((145, 235), (75, 155), (75, 170)),
)


class FidelityImportHold(ValueError):
    pass


def inspect(folder:Path) -> dict:
    try:
        m=write_or_verify(folder,False)  # Rebuild the exact generated bytes.
    except (OSError,ValueError,TypeError) as exc:
        raise FidelityImportHold("V2 source/manifest mismatch") from exc
    if (m["original_creator_approved_reference_sha256"]!=APPROVED_IMAGE_SHA256
        or m["creator_3d_art_approval"]!="NOT_GRANTED"
        or m["orbiter_authorized"] is not False
        or m["gameplay_modified"] is not False
        or m["native_unreal_import"]!="NOT_VERIFIED"):
        raise FidelityImportHold("Missing exact review-only authority")
    return {
        "stage":"REGENERATED_SOURCE_ONLY_NOT_NATIVE",
        "sha256":m["sha256"],
        "approved_image_sha256":APPROVED_IMAGE_SHA256,
        "candidate_destinations":DESTINATIONS,
        "creator_3d_art_approval":False,
        "orbiter_authorized":False,
    }


def bounds_ok(bounds, bands) -> bool:
    try:
        values=(float(bounds.box_extent.x)*2,float(bounds.box_extent.y)*2,
                float(bounds.box_extent.z)*2)
        return all(low<=size<=high for size,(low,high) in zip(values,bands))
    except (AttributeError,TypeError,ValueError,OverflowError):
        return False


def import_in_editor(folder:Path, preflight:dict) -> dict:
    try:
        import unreal
    except ImportError as exc:
        raise FidelityImportHold("A real Unreal Editor Python session is required") from exc
    for name in ("EditorAssetLibrary","AssetImportTask","AssetToolsHelpers",
                 "StaticMesh","load_asset"):
        if not hasattr(unreal,name):
            raise FidelityImportHold("Missing native editor API: "+name)

    lib=unreal.EditorAssetLibrary
    # Read every destination before touching any; import is isolated, but not
    # transactionally rollbackable across multiple Interchange import tasks.
    for dest in DESTINATIONS:
        if lib.does_directory_exist(dest) and lib.list_assets(dest,recursive=True,include_folder=False):
            raise FidelityImportHold("Review folder already populated; refuse overwrite: "+dest)

    imported=[]
    for idx,(name,dest) in enumerate(zip(FILES,DESTINATIONS)):
        task=unreal.AssetImportTask()
        task.set_editor_property("filename",str((folder/name).resolve(strict=True)))
        task.set_editor_property("destination_path",dest)
        task.set_editor_property("automated",True)
        task.set_editor_property("replace_existing",False)
        task.set_editor_property("save",True)
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
        # UE5.8 Interchange often nests meshes under StaticMeshes.
        paths=lib.list_assets(dest,recursive=True,include_folder=False)
        meshes=[]
        for path in paths:
            obj=unreal.load_asset(path)
            if isinstance(obj,unreal.StaticMesh):
                if not hasattr(obj,"get_bounds") or not bounds_ok(obj.get_bounds(),EXTENT_BANDS_CM[idx]):
                    raise FidelityImportHold("Native centimetre axis/bounds check failed: "+str(path))
                meshes.append(str(path))
        if len(meshes)!=1:
            raise FidelityImportHold("Expected one native StaticMesh in the isolated folder: "+dest)
        imported.append({"file":name,"folder":dest,"static_meshes":meshes})
    return {
        "stage":"UE_NATIVE_STATICMESH_IMPORT_AND_BOUNDS_PASS_ONLY",
        "original_creator_approved_image":preflight["approved_image_sha256"],
        "assets":imported,
        "actual_material_rendering":"NOT_VERIFIED",
        "approved_model_fidelity":"NOT_APPROVED",
        "physics_and_continuous_clearance":"NOT_VERIFIED",
        "orbiter_authorized":False,
    }


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--folder",required=True,type=Path)
    mode=p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check",action="store_true")
    mode.add_argument("--import-review",action="store_true")
    args=p.parse_args(argv)
    try:
        receipt=inspect(args.folder)
        if args.import_review:
            receipt["native"]=import_in_editor(args.folder,receipt)
        print(json.dumps(receipt,indent=2,sort_keys=True))
    except (FidelityImportHold,OSError,ValueError,KeyError,TypeError) as exc:
        p.exit(1,"V2 REVIEW HOLD: "+str(exc)+"\n")


if __name__=="__main__":
    main()
